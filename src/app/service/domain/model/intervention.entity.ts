/**
 * Represents the intervention a technician registered to complete a service request: the technical report
 * of the work. Technicians register it from the mobile application; owners only read it.
 *
 * It is identified by the UUID the technician's device generated (`client_generated_id`).
 */
export class Intervention {
  private readonly _service_request_id: number;
  private readonly _client_generated_id: string;
  private readonly _technician_id: number;
  private readonly _equipment_id: number;
  private readonly _diagnosis: string;
  private readonly _actions_taken: string;
  private readonly _spare_parts: readonly string[];
  private readonly _photo_evidence: readonly string[];
  private readonly _started_at: Date | null;
  private readonly _completed_at: Date | null;
  private readonly _duration_seconds: number | null;

  /**
   * @param intervention - An object containing the properties of the intervention.
   */
  public constructor(intervention: {
    service_request_id: number;
    client_generated_id: string;
    technician_id: number;
    equipment_id: number;
    diagnosis: string;
    actions_taken: string;
    spare_parts: readonly string[];
    photo_evidence: readonly string[];
    started_at: Date | null;
    completed_at: Date | null;
    duration_seconds: number | null;
  }) {
    this._service_request_id = intervention.service_request_id;
    this._client_generated_id = intervention.client_generated_id;
    this._technician_id = intervention.technician_id;
    this._equipment_id = intervention.equipment_id;
    this._diagnosis = intervention.diagnosis;
    this._actions_taken = intervention.actions_taken;
    this._spare_parts = intervention.spare_parts;
    this._photo_evidence = intervention.photo_evidence;
    this._started_at = intervention.started_at;
    this._completed_at = intervention.completed_at;
    this._duration_seconds = intervention.duration_seconds;
  }

  /** The service request the intervention completed. */
  get service_request_id(): number {
    return this._service_request_id;
  }
  /** The UUID generated by the technician's device, which identifies the intervention. */
  get client_generated_id(): string {
    return this._client_generated_id;
  }
  get technician_id(): number {
    return this._technician_id;
  }
  get equipment_id(): number {
    return this._equipment_id;
  }
  /** What the technician found. */
  get diagnosis(): string {
    return this._diagnosis;
  }
  /** What the technician did. */
  get actions_taken(): string {
    return this._actions_taken;
  }
  get spare_parts(): readonly string[] {
    return this._spare_parts;
  }
  /** References (URLs) of the photos taken; the backend validates neither their scheme nor host. */
  get photo_evidence(): readonly string[] {
    return this._photo_evidence;
  }
  get started_at(): Date | null {
    return this._started_at;
  }
  get completed_at(): Date | null {
    return this._completed_at;
  }
  /** How long the work took, in seconds. */
  get duration_seconds(): number | null {
    return this._duration_seconds;
  }
}
